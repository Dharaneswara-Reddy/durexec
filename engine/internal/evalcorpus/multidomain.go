// MultiDomain builds the balanced ten-domain corpus.
//
// It is deterministic — the same pairs in the same order on every run — and it
// refuses to return a corpus that is not balanced, because an unbalanced
// corpus silently reweights every overall figure computed from it.
func MultiDomain() ([]Pair, error) {
	byDomain := make(map[string][]Pair, len(DomainOrder))

	for _, name := range DomainOrder {
		set, ok := multiDomain[name]
		if !ok {
			return nil, fmt.Errorf("evalcorpus: DomainOrder names %q but there is no such domain", name)
		}
		pairs, err := buildDomain(name, set)
		if err != nil {
			return nil, err
		}
		byDomain[name] = pairs
	}

	// Interleave round-robin so any prefix of the corpus is balanced across
	// domains and across labels. The per-domain lists alternate duplicate and
	// distinct for the same reason.
	var out []Pair
	for i := 0; ; i++ {
		placed := false
		for _, name := range DomainOrder {
			if i < len(byDomain[name]) {
				out = append(out, byDomain[name][i])
				placed = true
			}
		}
		if !placed {
			break
		}
	}

	if err := validate(out); err != nil {
		return nil, err
	}
	return out, nil
}

// buildDomain turns one domain's records and contrasts into its pairs, and
// checks the arithmetic that keeps the corpus balanced.
func buildDomain(name string, set domainSet) ([]Pair, error) {
	byID := make(map[string]record, len(set.Records))
	ids := make([]string, 0, len(set.Records))
	for _, r := range set.Records {
		if len(r.Phrasings) < 4 {
			return nil, fmt.Errorf("evalcorpus: %s record %q has %d phrasings, want at least 4",
				name, r.ID, len(r.Phrasings))
		}
		if _, clash := byID[r.ID]; clash {
			return nil, fmt.Errorf("evalcorpus: %s has two records called %q", name, r.ID)
		}
		byID[r.ID] = r
		ids = append(ids, r.ID)
	}
	sort.Strings(ids)

	// Duplicates: the anchor phrasing against each of the others. Pairing
	// against the anchor rather than taking every combination keeps the count
	// per record fixed at three, which is what makes the domains equal in
	// weight. Every pair is still a genuine rewording — the anchor is the
	// terse form and the others are not.
	var dups []Pair
	for _, r := range set.Records {
		for j := 1; j < 4; j++ {
			dups = append(dups, Pair{
				ID:       fmt.Sprintf("md-%s-dup-%s-%d", name, r.ID, j),
				Domain:   name,
				Activity: set.Activity,
				Category: "paraphrase",
				Note:     "same action (" + r.What + "), reworded",
				A:        r.Phrasings[0],
				B:        r.Phrasings[j],
				Truth:    Duplicate,
			})
		}
	}

	// Distincts: three phrasing-for-phrasing pairs per contrast, so both
	// sides are written in the same style and the difference in meaning is
	// the only thing telling them apart.
	var dis []Pair
	for _, c := range set.Contrasts {
		a, ok := byID[c.A]
		if !ok {
			return nil, fmt.Errorf("evalcorpus: %s contrast names unknown record %q", name, c.A)
		}
		b, ok := byID[c.B]
		if !ok {
			return nil, fmt.Errorf("evalcorpus: %s contrast names unknown record %q", name, c.B)
		}
		for i := 0; i < 3; i++ {
			// HARDNESS IS MEASURED, NOT DECLARED. "Hard" means one thing in
			// this corpus — the two sides share most of their words, so
			// separating them takes more than noticing that they are about
			// different subjects — and the only honest way to know that is
			// to count the shared words. Declaring it by hand would let a
			// hard-negative precision figure be flattered by whatever the
			// author felt was difficult.
			//
			// This has a consequence worth naming: in the MESSAGE domain two
			// different messages to the same addressee genuinely share few
			// words, because that domain's deciding content IS the free text.
			// Those pairs come out NOT hard, so the message domain
			// contributes fewer hard negatives than the others. That is a
			// property of the shape, and it is reported rather than fixed.
			overlap := wordOverlap(a.Phrasings[i], b.Phrasings[i])
			hard := overlap >= MinNearMissOverlap
			note := c.Reason
			if c.Easy {
				note += " (two actions with nothing to do with each other)"
			}
			category := "contrast"
			if hard {
				category = "near-miss"
			}
			dis = append(dis, Pair{
				ID:       fmt.Sprintf("md-%s-dis-%s-vs-%s-%d", name, a.ID, b.ID, i),
				Domain:   name,
				Activity: set.Activity,
				Category: category,
				Hard:     hard,
				Note:     note,
				A:        a.Phrasings[i],
				B:        b.Phrasings[i],
				Truth:    Distinct,
			})
		}
	}

	if len(dups) != PairsPerClassPerDomain || len(dis) != PairsPerClassPerDomain {
		return nil, fmt.Errorf(
			"evalcorpus: domain %s produced %d duplicate and %d distinct pairs, want %d of each; "+
				"the corpus is balanced by construction and an unbalanced domain would reweight "+
				"every overall figure without saying so",
			name, len(dups), len(dis), PairsPerClassPerDomain)
	}

	// Alternate the two classes so a prefix of one domain's pairs is balanced
	// too, not only a prefix of the interleaved whole.
	out := make([]Pair, 0, len(dups)+len(dis))
	for i := 0; i < PairsPerClassPerDomain; i++ {
		out = append(out, dups[i], dis[i])
	}
	return out, nil
}

// MultiDomainShapes reports each domain's one-line field shape, for the
// report's header. A reader has to be able to see that the domains were
// chosen for the shape of their deciding fields and not for variety of nouns.
func MultiDomainShapes() map[string]string {
	out := make(map[string]string, len(multiDomain))
	for name, set := range multiDomain {
		out[name] = set.Shape
	}
	return out
}

// MultiDomainActivity reports the activity type a domain's pairs are
// scheduled under.
func MultiDomainActivity(domain string) string {
	return multiDomain[domain].Activity
}
