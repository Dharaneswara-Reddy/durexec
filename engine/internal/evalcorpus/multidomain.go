// ---------------------------------------------------------------------------
// THE MULTI-DOMAIN CORPUS: TEN DOMAINS, BALANCED BY CONSTRUCTION
// ---------------------------------------------------------------------------
//
// WHAT IT IS FOR. One question: how far does a way of finding deciding fields
// travel beyond the domain it was written for? That question cannot be asked
// of the flight corpus in flight.go, which has one domain, and it cannot be
// asked of docs/results/rephrase-live-model.csv, which has five domains and
// real model wordings but NO NEGATIVE CLASS — nothing in it tests whether a
// comparator wrongly suppresses an action that should have happened. This
// file supplies the missing half: designed negatives, in ten domains, in
// equal numbers.
//
// WHAT IT IS NOT. The labels are generated by construction, exactly as
// flight.go's are and with the same consequence: a pair is called a duplicate
// because it was written as two phrasings of one record, not because a person
// confirmed that a user would consider them interchangeable. Where that
// assumption is wrong the measured accuracy is wrong by the same amount. The
// real-wording evidence is the rephrase run; this is the controlled half, and
// neither substitutes for the other.
//
// THE DOMAINS WERE CHOSEN FOR THE SHAPE OF THEIR DECIDING FIELDS, not for
// variety of nouns. A field extractor that only understands one shape will
// show it:
//
//	flight        an ordered pair of places, a day, a part of the day, a count
//	payment       one sum of money, a currency, one recipient
//	refund        an opaque identifier and a reason
//	meeting       a person, a day, a clock time and a DURATION — a range
//	message       one addressee and a body that is almost all free text
//	order         a quantity, a product code and a delivery address
//	provisioning  a resource identifier and an irreversible verb
//	ticket        an identifier, a priority and free-text description
//	subscription  a named plan, a seat count and an EFFECTIVE DATE
//	shipment      a parcel identifier, a destination and a service level
//
// Every one is an action where doing it twice genuinely hurts: a second seat
// bought, a second payment sent, a second refund issued, a duplicate calendar
// invite, a second email, a second order shipped, a second server destroyed,
// a second ticket in the queue, a double-charged subscription, a parcel
// dispatched twice.
//
// BALANCE IS STRUCTURAL, NOT INCIDENTAL. Each domain contributes exactly
// fifteen duplicate pairs and fifteen distinct pairs, and the domains are
// interleaved round-robin, so ANY PREFIX of the corpus is balanced. A run
// killed a third of the way through leaves a third of the corpus with the
// same shape as the whole, which is what makes a partial run readable instead
// of merely incomplete.
//
// THE NEGATIVES ARE MOSTLY HARD. A distinct pair is built by taking two
// records that differ in ONE deciding field and pairing their phrasings
// index-for-index, so both sides are written in the same style and the only
// thing separating them is the field. validate() enforces that every pair
// filed as a near miss really does share at least half its words, so a
// precision figure measured here cannot be flattered by negatives that share
// nothing.

// DomainOrder fixes the order domains are reported and interleaved in. A map's
// iteration order would reshuffle every table between runs and make two
// reports needlessly hard to compare.
var DomainOrder = []string{
	"flight", "payment", "refund", "meeting", "message",
	"order", "provisioning", "ticket", "subscription", "shipment",
}

// PairsPerClassPerDomain is how many duplicates and how many distincts each
// domain contributes. It is asserted in MultiDomain rather than merely
// intended: a domain that silently contributed fewer pairs would weight the
// overall figures towards the others and nothing in the output would say so.
const PairsPerClassPerDomain = 15

// record is one real action, written down once with several phrasings a
// planner might plausibly produce for it. Any two phrasings of one record are
// the same action and form a duplicate pair.
type record struct {
	ID string

	// What is the action in canonical form, for the Note on every pair built
	// from it. It is prose for a human reader, never parsed.
	What string

	// Phrasings must number at least 4; the first is the anchor that the
	// duplicate pairs are built against.
	Phrasings []string
}

// against names two records that must never be confused and says what
// separates them.
type against struct {
	A, B   string
	Reason string

	// Easy says the two records have nothing to do with each other. It is
	// DESCRIPTIVE ONLY and appears in the pair's note: whether a pair counts
	// as a hard negative is measured from the words the two sides share, not
	// declared here. Two "unrelated" actions written from the same template
	// can still share most of their words — the subscription domain's are a
	// case in point — and the measurement is what the figure has to rest on.
	Easy bool
}

// domainSet is one domain's records and the contrasts between them.
type domainSet struct {
	// Activity is the activity type pairs in this domain are scheduled
	// under. It is the tool whose repeat is the harm.
	Activity string

	// Shape is the one-line description of what this domain's deciding
	// fields look like, printed in the report so a reader can see why the
	// domains were chosen.
	Shape string

	Records   []record
	Contrasts []against
}

