// ---------------------------------------------------------------------------
// THE HELD-OUT CORPUS: TEN DOMAINS NO EXTRACTOR WAS WRITTEN AGAINST
// ---------------------------------------------------------------------------
//
// WHY IT EXISTS. Every extractor in internal/idem/semantic was developed by
// reading the failures it produced on the flight corpus and on the ten-domain
// corpus in multidomain.go. A score on either is therefore partly a score on
// data the author has seen. This file is the answer to "does it work on a
// task nobody tuned it for?": ten further domains, written and committed
// BEFORE the generic-v2 extractor existed, and never used while developing
// it. A figure on this corpus is the only one in the evaluation that can be
// called out-of-sample.
//
// It is built by exactly the same rules as multidomain.go — five records of
// four phrasings per domain, five contrasts per domain, fifteen duplicates
// and fifteen distinct pairs each, hardness measured from shared words — so
// the two corpora's figures are directly comparable.
//
// The labels are generated by construction, with the same caveat as the
// other corpora: two phrasings of one record are called a duplicate because
// they were written that way, not because a person confirmed it.
//
// The phrasings deliberately include world-knowledge aliases a generic
// extractor cannot be expected to resolve without a lexicon (a ticker for a
// company, a city's short form), so that the corpus measures the honest
// ceiling of a vocabulary-free method rather than flattering it.

