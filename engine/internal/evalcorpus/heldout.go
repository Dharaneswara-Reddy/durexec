// HeldOut builds the held-out ten-domain corpus with the same rules as
// MultiDomain. Pair ids start "ho-" so a row can never be mistaken for one
// from the development corpus.
func HeldOut() ([]Pair, error) {
	byDomain := make(map[string][]Pair, len(HeldOutDomainOrder))
	for _, name := range HeldOutDomainOrder {
		set, ok := heldOut[name]
		if !ok {
			return nil, fmt.Errorf("evalcorpus: HeldOutDomainOrder names %q but there is no such domain", name)
		}
		pairs, err := buildDomain(name, set)
		if err != nil {
			return nil, err
		}
		for i := range pairs {
			pairs[i].ID = "ho-" + strings.TrimPrefix(pairs[i].ID, "md-")
		}
		byDomain[name] = pairs
	}
	var out []Pair
	for i := 0; ; i++ {
		placed := false
		for _, name := range HeldOutDomainOrder {
			if i < len(byDomain[name]) {
				out = append(out, byDomain[name][i])
				placed = true
			}
		}
		if !placed {
			break
		}
	}
	if err := validate(out); err != nil {
		return nil, err
	}
	return out, nil
}

// HeldOutActivity reports the activity type a held-out domain is scheduled under.
func HeldOutActivity(domain string) string { return heldOut[domain].Activity }
