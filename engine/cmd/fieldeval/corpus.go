// ---------------------------------------------------------------------------
// THREE CORPORA, AND WHY NONE OF THEM IS ENOUGH ALONE
// ---------------------------------------------------------------------------
//
//	flight-213     The published synthetic flight corpus. Its value is
//	               comparability: every number in
//	               docs/results/semantic-experiment-*.txt was measured on
//	               exactly these pairs, so an extractor's score here can be
//	               read against the published hybrid figure. Its weakness is
//	               that the hand-written extractor's vocabulary was written
//	               by reading it, which inflates that one arm and nothing
//	               can undo that.
//
//	multidomain    300 pairs in ten domains, balanced, with designed
//	               negatives. It is the ONLY corpus here that can report a
//	               false-positive rate, because it is the only one with pairs
//	               built to be nearly identical and genuinely different. Its
//	               weakness is that its wordings are the author's idea of how
//	               a model rewords a request.
//
//	rephrase-live  The genuine rewordings a real planner produced under a
//	               real simulated crash, read out of
//	               docs/results/rephrase-live-model.csv. Its value is that
//	               nothing about the wording is invented. Its weakness is
//	               total on the other side: it has NO negative class, so it
//	               can report detection and must never be used for precision.
//
// A reader who takes the overall line and ignores the per-corpus lines will
// get the wrong answer, which is why the report prints per corpus first.

// evalPair is one labelled pair with the corpus it came from.
type evalPair struct {
	Corpus string
	Pair   evalcorpus.Pair
}

const (
	corpusFlight      = "flight-213"
	corpusMultiDomain = "multidomain-300"
	corpusRephrase    = "rephrase-live"
)

// provenance is everything the report header has to state about the run.
type provenance struct {
	StartedAt  time.Time
	FinishedAt time.Time

	Endpoint      string
	EmbedModel    string
	Dim           int
	CacheDir      string
	CommandLine   string
	ResumeCommand string
	CSVPath       string

	TauLow, TauHigh float64
	MinAgreeing     int
	Repeat          int
	Arms            []string

	Corpora     []corpusSummary
	DomainShape map[string]string

	LLMModel     string
	LLMSkipped   bool
	LLMCallsMade int64
	LLMFailures  int64
	LLMNanos     int64

	EmbedCalls         int
	EmbedP50, EmbedP99 time.Duration

	// RephraseSource records where the live pairs came from, and
	// RephraseNote what had to be dropped from it and why.
	RephraseSource string
	RephraseNote   string

	// RephraseUsable and RephraseReworded are the denominator and numerator
	// of the rephrase rate: of the trials where both incarnations invoked the
	// commit tool, how many changed the words. It is the premise the whole
	// project rests on, so it is restated here with a confidence interval
	// rather than cited from another file as a bare percentage.
	RephraseUsable   int
	RephraseReworded int
}

type corpusSummary struct {
	Name       string
	Pairs      int
	Duplicates int
	Distincts  int
	Hard       int
	Domains    int
	Labels     string
}

// loadCorpora assembles every pair to be scored, in an order that keeps a
// partial run balanced: the corpora are concatenated, but each one is already
// interleaved internally, so stopping part way through any of them leaves a
// representative slice of it.
func loadCorpora(cfg config) ([]evalPair, *provenance, error) {
	prov := &provenance{
		Endpoint:    cfg.endpoint,
		EmbedModel:  cfg.model,
		Dim:         cfg.dim,
		CacheDir:    cfg.cacheDir,
		DomainShape: evalcorpus.MultiDomainShapes(),
	}
	want := map[string]bool{}
	for _, c := range strings.Split(cfg.corpora, ",") {
		want[strings.TrimSpace(strings.ToLower(c))] = true
	}

	var out []evalPair

	if want["multidomain"] {
		pairs, err := evalcorpus.MultiDomain()
		if err != nil {
			return nil, nil, err
		}
		for _, p := range pairs {
			out = append(out, evalPair{Corpus: corpusMultiDomain, Pair: p})
		}
		prov.Corpora = append(prov.Corpora, summarise(corpusMultiDomain, pairs,
			"generated by construction: two phrasings of one record are a duplicate, "+
				"two records that differ in one deciding field are a distinct pair"))
	}

	if want["flight"] {
		pairs, err := evalcorpus.Corpus()
		if err != nil {
			return nil, nil, err
		}
		for _, p := range pairs {
			out = append(out, evalPair{Corpus: corpusFlight, Pair: p})
		}
		prov.Corpora = append(prov.Corpora, summarise(corpusFlight, pairs,
			"generated by construction; the same 213 pairs every published semantic result "+
				"was measured on"))
	}

	if want["rephrase"] {
		path := cfg.rephraseCSV
		if path == "" {
			path = findRephraseCSV()
		}
		pairs, note, usable, reworded, err := loadRephrasePairs(path)
		if err != nil {
			// A missing live corpus is not a reason to abandon the run: the
			// other two still answer most of the question. It is recorded so
			// the report cannot imply the live pairs were scored.
			prov.RephraseNote = "NOT SCORED: " + err.Error()
			fmt.Fprintf(os.Stderr, "fieldeval: live rephrase pairs not loaded: %v\n", err)
		} else {
			for _, p := range pairs {
				out = append(out, evalPair{Corpus: corpusRephrase, Pair: p})
			}
			prov.RephraseSource = path
			prov.RephraseNote = note
			prov.RephraseUsable, prov.RephraseReworded = usable, reworded
			prov.Corpora = append(prov.Corpora, summarise(corpusRephrase, pairs,
				"REAL: every wording was produced by qwen/qwen3.8-27b on both sides of a "+
					"simulated crash. No negative class — detection only, never precision"))
		}
	}

	if len(out) == 0 {
		return nil, nil, fmt.Errorf("-corpora %q selected no pairs", cfg.corpora)
	}
	if cfg.limit > 0 {
		out, prov.Corpora = truncate(out, prov.Corpora, cfg.limit)
	}
	return out, prov, nil
}

func summarise(name string, pairs []evalcorpus.Pair, labels string) corpusSummary {
	s := corpusSummary{Name: name, Labels: labels}
	domains := map[string]bool{}
	for _, p := range pairs {
		s.Pairs++
		domains[p.Domain] = true
		if bool(p.Truth) {
			s.Duplicates++
		} else {
			s.Distincts++
			if p.Hard {
				s.Hard++
			}
		}
	}
	s.Domains = len(domains)
	return s
}

// findRephraseCSV looks for the live run's output beside the repository. The
// harness runs from engine/, and the results live one level up in
// docs/results, which is where every other result file in this project lives.
func findRephraseCSV() string {
	candidates := []string{
		filepath.Join("..", "docs", "results", "rephrase-live-model.csv"),
		filepath.Join("docs", "results", "rephrase-live-model.csv"),
	}
	for _, c := range candidates {
		if _, err := os.Stat(c); err == nil {
			return c
		}
	}
	return candidates[0]
}

// loadRephrasePairs turns the live run's trials into labelled pairs.
//
// WHICH ROWS ARE TAKEN, and why each exclusion is necessary:
//
//	arm must be lost-journal    the control arm's recovered planner did not
//	                            re-issue the action at all, so it has no pair.
//	outcome must be usable      both incarnations invoked the commit tool.
//	                            Anything else produced no second call to
//	                            compare.
//	drifted must be false       a drifted trial is the model planning a
//	                            DIFFERENT action, not rewording one. Labelling
//	                            it a duplicate would ask the comparators to
//	                            suppress work that should happen.
//	byte_identical must be false  an identical pair is caught by exact matching
//	                            and says nothing about any extractor. Keeping
//	                            them would inflate every arm by the same
//	                            amount, which flatters the weakest one most.
//
// Every surviving row is labelled DUPLICATE, because that is what it is: one
// goal, one action, two wordings. There are no distinct pairs to be had — the
// live run was not built to produce them — so this corpus can report
// detection and nothing else, and the report says so wherever it appears.
func loadRephrasePairs(path string) (pairs []evalcorpus.Pair, note string, usable, reworded int, err error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, "", 0, 0, err
	}
	defer f.Close()

	r := csv.NewReader(f)
	r.FieldsPerRecord = -1
	head, err := r.Read()
	if err != nil {
		return nil, "", 0, 0, fmt.Errorf("read header of %s: %w", path, err)
	}
	col := map[string]int{}
	for i, h := range head {
		col[strings.TrimSpace(h)] = i
	}
	need := []string{"trial_key", "arm", "domain", "commit_tool", "outcome",
		"before_args", "after_args", "byte_identical", "drifted"}
	for _, n := range need {
		if _, ok := col[n]; !ok {
			return nil, "", 0, 0, fmt.Errorf("%s has no %q column", path, n)
		}
	}

	var total, notUsable, identical, drifted, control int
	for {
		rec, err := r.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, "", 0, 0, fmt.Errorf("read %s: %w", path, err)
		}
		get := func(name string) string {
			i, ok := col[name]
			if !ok || i >= len(rec) {
				return ""
			}
			return strings.TrimSpace(rec[i])
		}
		total++
		switch {
		case get("arm") != "lost-journal":
			control++
			continue
		case get("outcome") != "usable":
			notUsable++
			continue
		case isTrue(get("drifted")):
			drifted++
			continue
		case isTrue(get("byte_identical")):
			identical++
			continue
		}
		before, after := get("before_args"), get("after_args")
		if before == "" || after == "" {
			notUsable++
			continue
		}
		pairs = append(pairs, evalcorpus.Pair{
			ID:       "live-" + get("trial_key"),
			Domain:   get("domain"),
			Activity: get("commit_tool"),
			Category: "live-reword",
			Note:     "a real planner's two wordings of one lost action",
			A:        before,
			B:        after,
			Truth:    evalcorpus.Duplicate,
		})
	}
	if len(pairs) == 0 {
		return nil, "", 0, 0, fmt.Errorf("%s yielded no usable reworded pairs", path)
	}
	// Usable means both incarnations invoked the commit tool, so there was a
	// pair to compare at all. The byte-identical and drifted trials are
	// usable and are part of that denominator; they are simply not pairs this
	// harness can score.
	usable = len(pairs) + identical + drifted
	reworded = len(pairs)
	note = fmt.Sprintf(
		"%d trials in the file; %d kept as genuine rewordings. Dropped: %d on the "+
			"journal-intact control arm (no second call), %d whose outcome was not usable, "+
			"%d byte-identical (exact matching already catches those), %d drifted (the model "+
			"planned a different action, so suppressing it would destroy real work)",
		total, len(pairs), control, notUsable, identical, drifted)
	return pairs, note, usable, reworded, nil
}

func isTrue(s string) bool {
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "true", "t", "yes", "y", "1":
		return true
	}
	return false
}

// truncate keeps the first n pairs of each corpus, for a smoke test, and
// rewrites the summaries so the header describes what was actually scored
// rather than what was available.
func truncate(pairs []evalPair, summaries []corpusSummary, n int) ([]evalPair, []corpusSummary) {
	kept := map[string]int{}
	var out []evalPair
	for _, p := range pairs {
		if kept[p.Corpus] >= n {
			continue
		}
		kept[p.Corpus]++
		out = append(out, p)
	}
	byName := map[string][]evalcorpus.Pair{}
	for _, p := range out {
		byName[p.Corpus] = append(byName[p.Corpus], p.Pair)
	}
	redone := make([]corpusSummary, 0, len(summaries))
	for _, s := range summaries {
		ns := summarise(s.Name, byName[s.Name], s.Labels+
			fmt.Sprintf(" [TRUNCATED to the first %d pairs: this is a smoke test, not a result]", n))
		redone = append(redone, ns)
	}
	return out, redone
}
