// ---------------------------------------------------------------------------
// Run status and provenance.
// ---------------------------------------------------------------------------

// runStatus collects everything that went wrong while the run was happening.
//
// It exists so that a partial run cannot be reported as a whole one. The
// semantic checker is built to degrade rather than fail — a model server that
// is down produces DISTINCT verdicts and a workflow that keeps running, which
// is right for the engine and completely wrong for a measurement. Degrading
// silently here would turn "the service was unreachable" into "recall is
// 0.00", and the two are indistinguishable on the page.
type runStatus struct {
	mu            sync.Mutex
	failures      map[string]string
	fallbacks     map[string]bool
	UniqueIntents int

	// The wrappers are held so their counters can be read at the end.
	cache    *embedCache
	caching  *cachingEmbedder
	retrying *retryEmbedder
}

func newRunStatus() *runStatus {
	return &runStatus{failures: map[string]string{}, fallbacks: map[string]bool{}}
}

func (s *runStatus) embedFailed(pairID string, err error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if _, ok := s.failures[pairID]; !ok {
		s.failures[pairID] = err.Error()
	}
}

func (s *runStatus) fellBack(pairID string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.fallbacks[pairID] = true
}

// provenance is the block that says where a number came from. Every output —
// the terminal, both CSVs and the HTML report — carries it, because a figure
// separated from its provenance is exactly the figure that ends up in a paper.
type provenance struct {
	StartedAt  time.Time
	FinishedAt time.Time

	EmbedderKind  string // "fake" or "http"
	EmbedderLabel string
	Model         string
	Endpoint      string
	Dim           int

	// Fake is the single most important field in this struct. When it is true
	// no semantic number in the run means anything, and every output has to
	// say so before it says anything else.
	Fake bool

	Corpus       CorpusSummary
	Repeat       int
	Arms         int
	ActivityType string

	TauMin, TauMax, TauStep, BandWidth float64

	CacheDir      string
	Cache         cacheStats
	Retries       int
	EmbedRetries  int
	UniqueIntents int

	// EmbedLatencies are the real model round-trips: the calls the cache could
	// not serve. They are the answer to "what does one embedding cost?", which
	// is a different question from "what does one check cost?".
	EmbedLatencies []time.Duration

	FailedPairs   []string
	FallbackPairs []string

	CommandLine string
}

// LabelsHandAssigned is false and is expected to stay false until a person has
// read the pairs.
//
// It is a method rather than a field so nothing can set it to true by filling
// in a struct literal. Turning it true is a change to this line, which is a
// change a reviewer sees.
func (p *provenance) LabelsHandAssigned() bool { return false }

// LabelSource is the one-line description printed wherever the labels are
// mentioned.
func (p *provenance) LabelSource() string {
	if p.LabelsHandAssigned() {
		return "hand-assigned by a human annotator"
	}
	return "generated by construction (no human labelled these pairs)"
}

// Incomplete reports whether any embedding could not be obtained.
//
// An incomplete run still prints its numbers, because the pairs that did
// succeed were really measured and throwing them away helps nobody. What it
// must never do is present those numbers as the run's result.
func (p *provenance) Incomplete() bool {
	return len(p.FailedPairs) > 0 || len(p.FallbackPairs) > 0
}

// IncompleteReasons explains, in plain words, why the run is not whole.
func (p *provenance) IncompleteReasons() []string {
	var out []string
	if n := len(p.FailedPairs); n > 0 {
		out = append(out, fmt.Sprintf(
			"%d pair(s) could not be embedded at all, even after %d attempts each. Their rows "+
				"are counted as DISTINCT because that is what the engine would do, but no "+
				"similarity was ever measured for them.", n, p.Retries))
	}
	if n := len(p.FallbackPairs); n > 0 {
		out = append(out, fmt.Sprintf(
			"%d pair(s) were decided by the checker's degraded path, which answers DISTINCT "+
				"without consulting the model. A similarity of 0.0000 on those rows is an "+
				"absent measurement, not a measured zero.", n))
	}
	return out
}

// SemanticNumbersAreReal reports whether the semantic arms measured meaning.
// It is the gate every headline in the report is written against.
func (p *provenance) SemanticNumbersAreReal() bool { return !p.Fake && !p.Incomplete() }

// Verdict is the one phrase that says what kind of run this was.
func (p *provenance) Verdict() string {
	switch {
	case p.Fake && p.Incomplete():
		return "SMOKE TEST, AND INCOMPLETE"
	case p.Fake:
		return "SMOKE TEST — NOT A RESULT"
	case p.Incomplete():
		return "INCOMPLETE RUN — NOT A RESULT"
	default:
		return "MEASURED AGAINST A REAL ENCODER"
	}
}

// Duration is how long the whole run took.
func (p *provenance) Duration() time.Duration { return p.FinishedAt.Sub(p.StartedAt) }

// finish reads the counters off the embedder stack once the run is over.
func (p *provenance) finish(st *runStatus) {
	st.mu.Lock()
	for id := range st.failures {
		p.FailedPairs = append(p.FailedPairs, id)
	}
	for id := range st.fallbacks {
		p.FallbackPairs = append(p.FallbackPairs, id)
	}
	p.UniqueIntents = st.UniqueIntents
	cache, caching, retrying := st.cache, st.caching, st.retrying
	st.mu.Unlock()

	// Sorted so two runs that failed on the same pairs produce byte-identical
	// reports, which is what makes a diff between two runs readable.
	sort.Strings(p.FailedPairs)
	sort.Strings(p.FallbackPairs)

	if cache != nil {
		p.Cache = cache.Stats()
	}
	if caching != nil {
		p.EmbedLatencies = caching.MissLatencies()
	}
	if retrying != nil {
		// Only the retry count is taken. The failure count is per call, and a
		// single unreachable pair produces two of them; FailedPairs is the
		// authority on how much of the corpus is missing.
		p.EmbedRetries, _ = retrying.Counters()
	}
}

// EmbedP50 and EmbedP99 describe one real model round-trip.
func (p *provenance) EmbedP50() time.Duration { return percentile(p.EmbedLatencies, 0.50) }
func (p *provenance) EmbedP99() time.Duration { return percentile(p.EmbedLatencies, 0.99) }

