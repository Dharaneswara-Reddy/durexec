func writeHeader(cfg config, prov *provenance) {
	sum := prov.Corpus
	fmt.Println("===========================================================================")
	fmt.Println(" SEMANTIC IDEMPOTENCY — DETECTION QUALITY AND COST")
	fmt.Println("===========================================================================")
	fmt.Printf(" run at        : %s\n", prov.StartedAt.Format(time.RFC3339))
	fmt.Printf(" embedder      : %s\n", prov.EmbedderLabel)
	fmt.Printf(" model         : %s\n", prov.Model)
	fmt.Printf(" activity      : %s\n", prov.ActivityType)
	fmt.Printf(" thresholds    : %d arms — tau swept %.2f to %.2f step %.2f, "+
		"escalation band width %.2f\n",
		prov.Arms, prov.TauMin, prov.TauMax, prov.TauStep, prov.BandWidth)
	fmt.Printf(" repetitions   : %d per pair, for the latency percentiles\n", prov.Repeat)
	fmt.Printf(" corpus        : %d pairs — %d labelled DUPLICATE, %d labelled DISTINCT "+
		"(%d of them hard)\n",
		sum.Total, sum.Duplicates, sum.Distincts, sum.HardDistincts)
	fmt.Printf(" labels        : %s\n", prov.LabelSource())
	if !prov.LabelsHandAssigned() {
		fmt.Println("                 a publishable precision/recall figure needs these pairs")
		fmt.Println("                 labelled by a person; until then every accuracy number is provisional")
	}
	if prov.CacheDir != "" {
		fmt.Printf(" cache         : %s, keyed by (model name, intent text)\n", prov.CacheDir)
	} else {
		fmt.Println(" cache         : disabled")
	}

	cats := make([]string, 0, len(sum.ByCategory))
	for k := range sum.ByCategory {
		cats = append(cats, k)
	}
	sort.Strings(cats)
	fmt.Print(" by category   : ")
	for i, c := range cats {
		if i > 0 {
			fmt.Print(", ")
		}
		fmt.Printf("%s=%d", c, sum.ByCategory[c])
	}
	fmt.Println()

	if prov.Fake {
		fmt.Println()
		banner([]string{
			"THESE NUMBERS DO NOT MEASURE SEMANTIC SIMILARITY.",
			"",
			"This run used FakeEmbedder, which turns text into a vector by hashing",
			"it. A hash has no notion of meaning: two ways of saying the same thing",
			"hash to unrelated vectors and score near zero.",
			"",
			"So every semantic arm below catches only the pairs that are identical",
			"after canonicalisation, and misses every genuinely reworded duplicate.",
			"A near-zero duplicate-detection rate here is the EXPECTED and CORRECT",
			"result for a hash embedder. It is not a finding about the contribution.",
			"",
			"What this run does establish: the corpus loads, the arms run, the",
			"thresholds are applied, the escalation band behaves, the metrics, the",
			"CSV and the HTML report are produced, and the per-check cost is measured.",
			"",
			"For real figures, run with -embedder=http against a sentence encoder,",
			"over the HAND-LABELLED corpus. See corpus.go.",
		})
	}
	fmt.Println()
}

// printIncomplete is the loud version of "some of this run did not happen".
func printIncomplete(prov *provenance) {
	if !prov.Incomplete() {
		return
	}
	lines := []string{"THIS RUN IS INCOMPLETE. DO NOT QUOTE ITS NUMBERS.", ""}
	for _, r := range prov.IncompleteReasons() {
		lines = append(lines, wrapTo(r, 70)...)
		lines = append(lines, "")
	}
	lines = append(lines,
		"An embedding that never arrived is not a similarity of zero. Fix the",
		"service and re-run before reading anything below as a measurement.")
	banner(lines)
	fmt.Println()
}

// wrapTo breaks a sentence into lines no wider than n, for the banner.
func wrapTo(s string, n int) []string {
	var out []string
	line := ""
	for _, w := range strings.Fields(s) {
		switch {
		case line == "":
			line = w
		case len([]rune(line))+1+len([]rune(w)) <= n:
			line += " " + w
		default:
			out = append(out, line)
			line = w
		}
	}
	if line != "" {
		out = append(out, line)
	}
	return out
}

// banner draws a boxed warning. The box is padded programmatically rather than
// by hand so a later edit to the wording cannot leave a ragged right edge.
func banner(lines []string) {
	width := 0
	for _, l := range lines {
		if len([]rune(l)) > width {
			width = len([]rune(l))
		}
	}
	edge := " " + strings.Repeat("*", width+6)
	fmt.Println(edge)
	for _, l := range lines {
		fmt.Printf(" *  %s%s  *\n", l, strings.Repeat(" ", width-len([]rune(l))))
	}
	fmt.Println(edge)
}

