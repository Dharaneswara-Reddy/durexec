// armResult accumulates one arm's confusion matrix and latency samples.
//
// The counting rule for ESCALATE is the one decision in this file that changes
// what the numbers mean, so it is written down rather than left implicit.
//
// When the engine escalates it does NOT skip the activity. It stops and asks a
// person. So an escalated verdict is never a false positive: nothing was
// wrongly suppressed. But it is also not a catch: the duplicate was not caught
// automatically. Escalations are therefore counted as "not a duplicate" for
// precision and recall, and reported separately in their own columns so a
// reader can see how much of the recall shortfall is a silent miss and how much
// is a deferral to a human.
//
// That accounting is deliberately unkind to the escalation arm on recall and
// kind to it on precision, which is exactly the trade the escalation band is
// meant to make.
type armResult struct {
	Arm      arm
	Embedder string
	Pairs    int

	TruePositives  int // a real duplicate, called a duplicate
	FalsePositives int // a distinct request, called a duplicate — the dangerous error
	TrueNegatives  int // a distinct request, not called a duplicate
	FalseNegatives int // a real duplicate, not called a duplicate

	EscalatedDuplicates int // real duplicates sent to a human
	EscalatedDistincts  int // distinct requests sent to a human
	Fallbacks           int // checks that degraded because the model was unreachable

	// The same counts restricted to the hard negatives — the distinct pairs
	// that share most of their words with their partner. Precision over the
	// whole set is inflated by pairs that no method would confuse; these
	// columns are the ones that carry information.
	HardDistincts      int
	HardFalsePositives int

	Latencies []time.Duration
}

func newArmResult(a arm, pairs int) *armResult {
	return &armResult{Arm: a, Pairs: pairs, Latencies: make([]time.Duration, 0, pairs)}
}

func (r *armResult) record(p Pair, o outcome) {
	if o.Fallback {
		r.Fallbacks++
	}
	dup := o.Verdict == core.VerdictDuplicate
	esc := o.Verdict == core.VerdictEscalate

	if p.Truth == Distinct && p.Hard {
		r.HardDistincts++
		if dup {
			r.HardFalsePositives++
		}
	}

	switch {
	case bool(p.Truth) && dup:
		r.TruePositives++
	case bool(p.Truth):
		r.FalseNegatives++
		if esc {
			r.EscalatedDuplicates++
		}
	case dup:
		r.FalsePositives++
	default:
		r.TrueNegatives++
		if esc {
			r.EscalatedDistincts++
		}
	}
}

func (r *armResult) trueDuplicates() int { return r.TruePositives + r.FalseNegatives }
func (r *armResult) trueDistincts() int  { return r.FalsePositives + r.TrueNegatives }

// MadePositivePredictions reports whether this arm ever said DUPLICATE.
//
// It is the guard on precision. Precision is the share of the suppressions that
// were right, and an arm that suppressed nothing made no suppressions to be
// right or wrong about: the fraction is 0/0, which is undefined rather than
// zero. A threshold of 0.99 against a corpus whose best score is 0.97 is
// exactly that case, and a sweep that runs to 0.99 will meet it.
//
// Precision() still returns 0 there, because a table cell reading "NaN" is
// read as a broken program rather than as an absent measurement. But a 0 is a
// value, and drawing it would put a point on the floor of the chart and make
// the curve look as though it collapsed at high thresholds. So the chart asks
// this question first and leaves such arms off the line, naming them in the
// caption instead; see writeSeries in chart.go and the caption in html.go.
//
// An escalated verdict is not a positive prediction. The engine did not
// suppress anything when it escalated — it stopped and asked a person — so an
// arm whose band swallowed every high score has still predicted nothing
// positive, and its precision is still undefined.
func (r *armResult) MadePositivePredictions() bool {
	return r.TruePositives+r.FalsePositives > 0
}

// PrecisionIsDefined is MadePositivePredictions said from the reader's side.
// The two names exist because the call sites ask two different questions of the
// same fact, and a chart reading "if !r.PrecisionIsDefined()" is clearer about
// why the point is missing than one reading "if no positives".
func (r *armResult) PrecisionIsDefined() bool { return r.MadePositivePredictions() }

// DuplicateDetectionRate is the share of real duplicates the arm caught by
// itself. It is numerically the same as recall; both are printed because the
// design document names them separately.
func (r *armResult) DuplicateDetectionRate() float64 {
	return ratio(r.TruePositives, r.trueDuplicates())
}

// FalsePositiveRate is the share of genuinely distinct requests that were
// wrongly called duplicates. This is the number that matters most: a false
// positive means a seat that should have been booked was not.
func (r *armResult) FalsePositiveRate() float64 {
	return ratio(r.FalsePositives, r.trueDistincts())
}

// HardFalsePositiveRate is the share of the lexically-close distinct pairs
// that were wrongly suppressed. It is the honest version of FalsePositiveRate:
// a method can score a perfect 0.000 overall simply because most of the
// negatives in the corpus were easy.
func (r *armResult) HardFalsePositiveRate() float64 {
	return ratio(r.HardFalsePositives, r.HardDistincts)
}

// Precision is the share of the arm's suppressions that were right.
//
// It reports 0 when the arm suppressed nothing at all, where the true answer
// is "undefined". Read it together with MadePositivePredictions, which is what
// tells the two cases apart.
func (r *armResult) Precision() float64 {
	return ratio(r.TruePositives, r.TruePositives+r.FalsePositives)
}

func (r *armResult) Recall() float64 {
	return ratio(r.TruePositives, r.TruePositives+r.FalseNegatives)
}

func (r *armResult) F1() float64 {
	p, rec := r.Precision(), r.Recall()
	if p+rec == 0 {
		return 0
	}
	return 2 * p * rec / (p + rec)
}

// EscalationRate is the share of all pairs handed to a human.
func (r *armResult) EscalationRate() float64 {
	return ratio(r.EscalatedDuplicates+r.EscalatedDistincts, r.Pairs)
}

func (r *armResult) P50() time.Duration  { return percentile(r.Latencies, 0.50) }
func (r *armResult) P99() time.Duration  { return percentile(r.Latencies, 0.99) }
func (r *armResult) Mean() time.Duration { return meanDuration(r.Latencies) }

// ratio guards against 0/0, which would otherwise print as NaN and look like a
// measurement rather than an absence of one.
func ratio(num, den int) float64 {
	if den == 0 {
		return 0
	}
	return float64(num) / float64(den)
}

// percentile uses nearest-rank on a sorted copy. With a few hundred samples the
// difference between nearest-rank and an interpolating definition is far below
// the timer's own resolution, and nearest-rank always returns a duration that
// was actually observed.
func percentile(d []time.Duration, p float64) time.Duration {
	if len(d) == 0 {
		return 0
	}
	sorted := append([]time.Duration(nil), d...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i] < sorted[j] })
	idx := int(float64(len(sorted))*p+0.9999) - 1
	if idx < 0 {
		idx = 0
	}
	if idx >= len(sorted) {
		idx = len(sorted) - 1
	}
	return sorted[idx]
}

func meanDuration(d []time.Duration) time.Duration {
	if len(d) == 0 {
		return 0
	}
	var total time.Duration
	for _, x := range d {
		total += x
	}
	return total / time.Duration(len(d))
}

// perPairRow is one arm's decision on one pair, kept for the detail CSV and the
// error analysis.
type perPairRow struct {
	ArmName string
	Arm     arm
	Pair    Pair
	Outcome outcome
}

// Correct reports whether the verdict matched the ground truth. An ESCALATE is
// counted as not correct, because the engine did not resolve the pair on its
// own; see the note on armResult.
func (r perPairRow) Correct() bool {
	if bool(r.Pair.Truth) {
		return r.Outcome.Verdict == core.VerdictDuplicate
	}
	return r.Outcome.Verdict == core.VerdictDistinct
}

// Dangerous reports the error that costs a user money: a genuinely new request
// suppressed as though it were a repeat.
func (r perPairRow) Dangerous() bool {
	return !bool(r.Pair.Truth) && r.Outcome.Verdict == core.VerdictDuplicate
}

