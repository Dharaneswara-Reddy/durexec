// printBest names the arm with the highest F1 on each semantic series.
//
// It is printed because a thirty-point sweep otherwise invites the reader to
// find the best point themselves, which is the same thing as choosing the
// threshold after seeing the answers. Naming it here makes the selection
// explicit and reviewable.
func printBest(results []*armResult) {
	fmt.Println("BEST ARM ON EACH SERIES, BY F1")
	fmt.Println()
	for _, series := range []string{seriesSingle, seriesBand} {
		var best *armResult
		for _, r := range results {
			if r.Arm.Series != series {
				continue
			}
			if best == nil || r.F1() > best.F1() {
				best = r
			}
		}
		if best == nil {
			continue
		}
		fmt.Printf("  %-18s %-30s precision %s  recall %.3f  F1 %.3f  hardFPR %.3f\n",
			series, best.Arm.Name, precisionText(best), best.Recall(), best.F1(),
			best.HardFalsePositiveRate())
	}
	fmt.Println()
	fmt.Println("  Choosing a threshold by the F1 it scored on this corpus is selection on the")
	fmt.Println("  test set. A threshold to ship has to be chosen on a held-out split.")
	fmt.Println()
}

// printFixtureVerdicts singles out the DoubleBooking pair. The whole evaluation
// is built around that one scenario, so its verdict is quoted directly rather
// than left for a reader to dig out of a CSV.
func printFixtureVerdicts(rows []perPairRow) {
	fmt.Println("THE DOUBLE-BOOKING FIXTURE (app/agent)")
	fmt.Println()

	var found bool
	for _, r := range rows {
		if r.Pair.Category != "fixture" || !r.Arm.Landmark {
			continue
		}
		if !found {
			fmt.Printf("  before the crash : %q\n", r.Pair.A)
			fmt.Printf("  after  the crash : %q\n", r.Pair.B)
			fmt.Printf("  ground truth     : %s — the same booking, reworded\n\n", r.Pair.Truth)
			found = true
		}
		mark := "MISSED — a second seat would be booked"
		switch r.Outcome.Verdict {
		case core.VerdictDuplicate:
			mark = "CAUGHT — the repeat is suppressed"
		case core.VerdictEscalate:
			mark = "ESCALATED — a human is asked before booking"
		}
		fmt.Printf("  %-29s similarity %.4f  %-9s  %s\n",
			r.ArmName, r.Outcome.Similarity, r.Outcome.Verdict, mark)
	}
	if !found {
		fmt.Println("  (no fixture pair in the corpus)")
	}
	fmt.Println()
	fmt.Println("  Only the landmark thresholds are listed; the full sweep is in the CSV and")
	fmt.Println("  the HTML report.")
	fmt.Println()
}

// printBreakdown reports each arm's recall split by how the duplicate was made.
// The split is the useful part: the surface category is caught by normalisation
// alone and proves the harness is wired up, while the paraphrase category is
// the one that actually requires meaning.
func printBreakdown(results []*armResult, rows []perPairRow) {
	fmt.Println("DUPLICATES CAUGHT, BY HOW THE DUPLICATE WAS MADE")
	fmt.Println()

	cats := []string{"fixture", "surface", "paraphrase"}
	fmt.Printf(" %-29s", "arm")
	for _, c := range cats {
		fmt.Printf(" | %-17s", c)
	}
	fmt.Println()
	fmt.Println(" " + strings.Repeat("-", 29) + strings.Repeat("-+------------------", len(cats)))

	for _, res := range results {
		if !res.Arm.Landmark {
			continue
		}
		fmt.Printf(" %-29s", trunc(res.Arm.Name, 29))
		for _, c := range cats {
			caught, total := 0, 0
			for _, r := range rows {
				if r.ArmName != res.Arm.Name || r.Pair.Category != c {
					continue
				}
				total++
				if r.Outcome.Verdict == core.VerdictDuplicate {
					caught++
				}
			}
			fmt.Printf(" | %3d/%-3d %6.1f%%  ", caught, total, 100*ratio(caught, total))
		}
		fmt.Println()
	}
	fmt.Println()
}

func printMistakes(rows []perPairRow) {
	fmt.Println("MISCLASSIFIED PAIRS")
	fmt.Println()
	shown := 0
	for _, r := range rows {
		if r.Correct() {
			continue
		}
		flag := " "
		if r.Dangerous() {
			flag = "!" // a distinct request suppressed: the expensive direction
		}
		fmt.Printf(" %s %-29s %-26s truth=%-9s got=%-9s sim=%.4f  %q vs %q\n",
			flag, trunc(r.ArmName, 29), trunc(r.Pair.ID, 26),
			r.Pair.Truth, r.Outcome.Verdict, r.Outcome.Similarity, r.Pair.A, r.Pair.B)
		shown++
	}
	if shown == 0 {
		fmt.Println(" (none)")
	}
	fmt.Printf("\n %d misclassified rows; '!' marks a distinct request wrongly suppressed\n\n", shown)
}

