// The three columns below are prose, not booleans, on purpose. A column
// reading "FALSE" invites a reader to filter it out and forget it; a column
// reading "no - generated by construction, see corpus.go" survives being
// pasted into a spreadsheet and then into a draft.

func labelColumn(prov *provenance) string {
	if prov.LabelsHandAssigned() {
		return "yes - hand-assigned"
	}
	return "no - generated by construction, see corpus.go"
}

func embedderColumn(prov *provenance) string {
	if prov.Fake {
		return "no - FakeEmbedder hashes text, these semantic rows are placeholders"
	}
	return "yes - " + prov.Model
}

func completeColumn(prov *provenance) string {
	if prov.Incomplete() {
		return fmt.Sprintf("no - %d pair(s) failed, %d fell back to the degraded path",
			len(prov.FailedPairs), len(prov.FallbackPairs))
	}
	return "yes - every pair was embedded"
}

func newCSV(path string) (*csv.Writer, func(), error) {
	if dir := filepath.Dir(path); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return nil, nil, fmt.Errorf("create %s: %w", dir, err)
		}
	}
	file, err := os.Create(path)
	if err != nil {
		return nil, nil, fmt.Errorf("create %s: %w", path, err)
	}
	return csv.NewWriter(file), func() { _ = file.Close() }, nil
}

// ---------------------------------------------------------------------------
// Small formatting helpers.
// ---------------------------------------------------------------------------

func f(v float64) string { return strconv.FormatFloat(v, 'f', 4, 64) }

// precisionText is precision for a human reader: three decimals, or "undef"
// when the arm made no positive predictions and the ratio is 0/0.
func precisionText(r *armResult) string {
	if !r.PrecisionIsDefined() {
		return "undef"
	}
	return fmt.Sprintf("%.3f", r.Precision())
}

// precisionCSV leaves the cell EMPTY when precision is undefined. An empty
// cell is what a spreadsheet treats as missing, so an average or a chart over
// the column skips it; a 0.0000 would be averaged in as a real score.
func precisionCSV(r *armResult) string {
	if !r.PrecisionIsDefined() {
		return ""
	}
	return f(r.Precision())
}

// us reports a duration in microseconds. The CSV carries a bare number so a
// spreadsheet can chart it without first parsing "1.2ms".
func us(d time.Duration) string {
	return strconv.FormatFloat(float64(d.Nanoseconds())/1000.0, 'f', 3, 64)
}

func fmtDur(d time.Duration) string {
	switch {
	case d < time.Microsecond:
		return fmt.Sprintf("%dns", d.Nanoseconds())
	case d < time.Millisecond:
		return fmt.Sprintf("%.1fus", float64(d.Nanoseconds())/1000)
	default:
		return fmt.Sprintf("%.2fms", float64(d.Nanoseconds())/1e6)
	}
}

func trunc(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n-1] + "…"
}
